RANDOM_SEED = 42            # 고정하면 매번 같은 움직임 → before/after 비교가 가능해짐

# ── 창고 공간 ────────────────────────────────
WAREHOUSE_SIZE = 100.0      # 100m × 100m 정사각형
MAX_ALTITUDE = 20.0         # 드론 최대 고도(m). 지상 로봇은 항상 z=0

# ── 배치 저장 ────────────────────────────────
BATCH_INTERVAL_SEC = 5      # 몇 초마다 DB에 "쓸지" (쓰기 횟수)
# ↑ 이 값이 "장애 시 유실량" — 서버가 죽으면 최대 이만큼이 날아감

TELEMETRY_SAMPLE_EVERY_TICKS = 10   # 몇 tick마다 "기록할지" (데이터 양)
# ↑ 이 값이 "데이터 해상도". 10 tick = 1초에 한 번.
#
# ⚠️ 이 둘은 다른 손잡이입니다. 헷갈리면 안 됩니다.
#      BATCH_INTERVAL_SEC          = 얼마나 몰아서 쓰나  (버퍼링)
#      TELEMETRY_SAMPLE_EVERY_TICKS = 얼마나 자주 남기나  (샘플링)
#
# 왜 샘플링이 필요한가 — 실측으로 확인한 것:
#   매 tick 기록(=이 값이 1)으로 서버를 6분 22초 돌렸더니
#     · telemetry 3,651,000행, DB 482MB + WAL 107MB
#     · flush 소요가 10.5s → 24.0s → 44.0s 로 계속 증가 (배치 주기는 5초)
#     · 버퍼 초과로 1,429,000행 폐기, COUNT(*) 한 번에 57초
#   flush 가 배치 주기를 넘기면 버퍼가 더 쌓이고 → 다음 flush 가 더 커지고 →
#   더 느려지는 **죽음의 나선**입니다. 되돌아오지 못합니다.
#
#   배치(버퍼링)는 "어떻게 쓰느냐"를 고칠 뿐 "얼마나 쓰느냐"는 못 고칩니다.
#   초당 1만 행을 계속 만들어내면 어떤 쓰기 전략으로도 결국 밀립니다.
#
# 저장량 계산 (로봇 1,000대 기준):
#     1  (매 tick)  10,000행/초  ≈ 5.5 GB/시간   ← 터짐. 위 실측이 이것
#     10 (1초)       1,000행/초  ≈ 480 MB/시간   ← 현재 값
#     50 (5초)         200행/초  ≈  96 MB/시간   ← 기획서 원안, 더 안전
#
# 무엇을 잃나: 두 샘플 사이의 움직임입니다.
#   · "지난 1시간 이동 경로" → 1초 간격 점을 이으면 충분합니다. OK
#   · "충돌 직전 0.3초에 뭐가 있었나" → ❌ 데이터가 없습니다.
#   실시간 화면은 어차피 메모리(WebSocket)에서 나오므로 영향 없습니다.

# ── 알림 판정 규칙 ───────────────────────────
